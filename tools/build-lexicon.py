"""Writes data/lexicon.js from content/lexicon-words.tsv: the words written solid (每天, 前边 ...) with their pinyin.

The AI conversation uses it to space and spell the pinyin of a reply the same way the content builders do (the HSK lists alone would split
these words per character). Run it after editing content/lexicon-words.tsv:  python3 tools/build-lexicon.py
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
os.environ.setdefault('LEVEL', '2')
import levelcfg
from pinyin_engine import Engine, read_tsv, C, ROOT

eng = Engine(levelcfg.known())
rows = {}
for _, r in read_tsv(os.path.join(C, 'lexicon-words.tsv')):
    rows[r[0]] = eng.word_py(r[0])
out = os.path.join(ROOT, 'data', 'lexicon.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build-lexicon.py from content/lexicon-words.tsv. Do not edit.\n')
    f.write('window.SHANLU_LEXICON = ' + json.dumps(rows, ensure_ascii=False, indent=0) + ';\n')
print('lexicon: %d words' % len(rows))
