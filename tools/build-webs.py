#!/usr/bin/env python3
"""Build data/hsk1-webs.js (shared-character groups, opposite pairs, topics) from content/webs.json.

Checks while building:
  - every word named exists in the HSK 1 list
  - every word in a shared-character group contains the group character, and its two parts add up to the word
  - every fill-in sentence has one blank and its answer is among its options
  - every one of the 300 words belongs to at least one topic (so every word can be started from the Word webs screen)
Run:  python3 tools/build-webs.py
"""
import json, os, sys, unicodedata, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pinyin_engine import Engine
from pypinyin import lazy_pinyin, Style

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content')


def toneless(py):
    s = unicodedata.normalize('NFD', py)
    return re.sub(r"[^a-z]", '', ''.join(c for c in s if not unicodedata.combining(c)).lower())


def die(m):
    sys.exit('build-webs: ' + m)


def main():
    official = [l.strip() for l in open(os.path.join(C, 'hsk1-official-300.txt'), encoding='utf-8') if l.strip()]
    ow = set(official)
    eng = Engine(official)
    src = json.load(open(os.path.join(C, 'webs.json'), encoding='utf-8'))

    hubs = []
    for h in src['hubs']:
        hz = h['hub']
        if toneless(h['py']) != toneless(''.join(lazy_pinyin(hz, style=Style.TONE))):
            die('hub %s: pinyin %s does not match pypinyin' % (hz, h['py']))
        words = []
        for z, c1, g1, c2, g2 in h['words']:
            if z not in ow:
                die('hub %s: %s is not an HSK 1 word' % (hz, z))
            if hz not in z:
                die('hub %s: word %s does not contain the character' % (hz, z))
            if c1 + c2 != z:
                die('hub %s: parts of %s are %s + %s' % (hz, z, c1, c2))
            words.append(dict(zh=z, parts=[[c1, g1], [c2, g2]]))
        wset = {w['zh'] for w in words}
        gaps = []
        for g in h['gaps']:
            if g['zh'].count('___') != 1:
                die('hub %s: gap needs exactly one blank: %s' % (hz, g['zh']))
            if g['ans'] not in g['opts'] or any(o not in ow for o in g['opts']) or len(set(g['opts'])) != len(g['opts']):
                die('hub %s: bad options in %s' % (hz, g['zh']))
            gaps.append(dict(en=g['en'], zh=g['zh'], ans=g['ans'], opts=g['opts']))
        hubs.append(dict(hub=hz, py=h['py'], en=h['en'], words=words, gaps=gaps))

    opps = []
    for o in src['opps']:
        if o['a'] not in ow or o['b'] not in ow:
            die('opposites: %s / %s not both HSK 1 words' % (o['a'], o['b']))
        opps.append(dict(a=o['a'], b=o['b'], note=o['note']))

    topics, seen = [], set()
    for t in src['topics']:
        for z in t['words']:
            if z not in ow:
                die('topic %s: %s is not an HSK 1 word' % (t['name'], z))
        if len(set(t['words'])) != len(t['words']):
            die('topic %s: duplicate words' % t['name'])
        seen.update(t['words'])
        py, _ = eng.sentence(t['sentence']['zh'])
        topics.append(dict(name=t['name'], to=t['to'], cta=t['cta'], sentence=dict(zh=t['sentence']['zh'], py=py, en=t['sentence']['en']), words=t['words']))
    missing = [z for z in official if z not in seen]
    if missing:
        die('words that are in no topic: %s' % ' '.join(missing))

    with open(os.path.join(ROOT, 'data', 'hsk1-webs.js'), 'w', encoding='utf-8') as f:
        f.write('/* HSK 1 word webs for Shanlu. GENERATED by tools/build-webs.py from content/webs.json. Do not edit by hand.\n')
        f.write(' * Character meanings inside words ("parts") are simple glosses written by AI. They are NOT reviewed by a human teacher. */\n')
        f.write('window.HSK1_WEBS = ' + json.dumps(dict(hubs=hubs, opps=opps, topics=topics), ensure_ascii=False, indent=1) + ';\n')
    print('wrote data/hsk1-webs.js: %d character groups, %d opposite pairs, %d topics; all %d words are in a topic' % (len(hubs), len(opps), len(topics), len(official)))


if __name__ == '__main__':
    main()
