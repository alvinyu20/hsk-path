#!/usr/bin/env node
/* Lists every string that changes when the 儿 endings are switched off, as "before -> after", so a person can read them all.
 * Usage: node tools/erhua-diff.js > review/HSK1-plain-forms.md
 */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'data');
const load = () => { global.window = {}; fs.readdirSync(dir).filter(f => /^hsk1(-.*)?\.js$/.test(f)).forEach(f => { delete require.cache[path.join(dir, f)]; require(path.join(dir, f)); }); return global.window; };
const std = JSON.parse(JSON.stringify(load()));
const win = load();
require(path.join(__dirname, '..', 'erhua.js')).make(win.HSK1_ERHUA).apply(win);
const plain = JSON.parse(JSON.stringify(win));

const rows = [];
const walk = (a, b, where) => {
  if (typeof a === 'string' && typeof b === 'string') { if (a !== b) rows.push([where, a, b]); return; }
  if (Array.isArray(a) && Array.isArray(b)) {
    if (a.length !== b.length) {
      // a list that got shorter (duplicates merged): show both lists whole, not item by item
      const label = (x) => (typeof x === 'string' ? x : x && x.zh ? x.zh : x && x.a ? x.a + '/' + x.b : JSON.stringify(x));
      rows.push([where, a.map(label).join(', '), b.map(label).join(', ')]);
      return;
    }
    a.forEach((x, i) => walk(x, b[i], where + '[' + i + ']'));
    return;
  }
  if (a && b && typeof a === 'object' && typeof b === 'object') Object.keys(a).forEach(k => walk(a[k], b[k], where + '.' + k));
};
['HSK1_WORDS', 'HSK1_GRAMMAR', 'HSK1_WEBS', 'HSK1_SPEAK', 'HSK1_LISTEN'].forEach(k => {
  // the word list loses three entries, so compare it by word instead of by position
  if (k === 'HSK1_WORDS') {
    const dropped = std[k].map(w => w.zh).filter(z => !plain[k].some(w => w.zh === z)).filter(z => win.HSK1_ERHUA.pairs.some(p => p.twin && p.official === z));
    dropped.forEach(z => rows.push(['HSK1_WORDS', z + ' (word)', '(left out: its plain twin is already on the list)']));
    const kept = std[k].filter(w => dropped.indexOf(w.zh) < 0);
    kept.forEach((w, i) => walk(w, plain[k][i], 'word:' + w.zh));
  } else walk(std[k], plain[k], k);
});
console.log('# What changes when 儿 endings are switched off\n');
console.log('Generated by tools/erhua-diff.js. ' + rows.length + ' differences. Read every line: each should be a correct, natural plain-Mandarin version of the line before it.\n');
console.log('| Where | With 儿 (exam style) | Plain (default) |\n|---|---|---|');
rows.forEach(r => console.log('| ' + r.map(x => String(x).replace(/\|/g, '\\|')).join(' | ') + ' |'));
