#!/usr/bin/env python3
"""List the recorded audio files in audio/ in data/audio-manifest.js, so the site plays them instead of the browser voice.

A file is named exactly like the text it speaks, plus an extension: 你好.mp3, 我想喝茶.mp3 (also .m4a, .ogg, .wav, .webm).
Files made by tools/make-audio.py (the Qwen voice) are named by a short hash and listed in audio/index.json (text -> file name); they are added too.
In the manifest, a plain extension ("mp3") means audio/<text>.<ext>; a value with a dot ("3f9a....mp3") is the file name itself. A key that starts with "m|" is the man's voice.
The site matches the text exactly as shown on screen, so a word or sentence that is written differently in the 儿 style needs its own file.
Run:  python3 tools/build-audio.py
"""
import json, os, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO = os.path.join(ROOT, 'audio')
EXT = ('.mp3', '.m4a', '.ogg', '.wav', '.webm')
RANK = {e: i for i, e in enumerate(EXT)}      # when one text has several files, the first extension in this list wins


def main():
    found = {}
    idx = os.path.join(AUDIO, 'index.json')
    made = json.load(open(idx, encoding='utf-8')) if os.path.exists(idx) else {}
    madefiles = set(made.values())
    for name in sorted(os.listdir(AUDIO)) if os.path.isdir(AUDIO) else []:
        if name in madefiles:
            continue
        stem, ext = os.path.splitext(unicodedata.normalize('NFC', name))
        if ext.lower() not in EXT:
            continue
        if stem not in found or RANK[ext.lower()] < RANK['.' + found[stem]]:
            found[stem] = ext.lower()[1:]
    for text, file in made.items():
        if os.path.exists(os.path.join(AUDIO, file)):
            found[unicodedata.normalize('NFC', text)] = file
    with open(os.path.join(ROOT, 'data', 'audio-manifest.js'), 'w', encoding='utf-8') as f:
        f.write('/* Recorded audio for Shanlu. GENERATED by tools/build-audio.py from the files in audio/. Do not edit by hand.\n')
        f.write(' * Each key is the exact text a recording speaks; the value is the file extension (audio/<text>.<ext>) or, with a dot, the file name itself. A key starting with m| is the man voice. Texts without a file are read by the browser voice or the live Qwen voice. */\n')
        f.write('window.SHANLU_AUDIO = ' + json.dumps(found, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n')
    print('wrote data/audio-manifest.js: %d recordings' % len(found))


if __name__ == '__main__':
    sys.exit(main())
