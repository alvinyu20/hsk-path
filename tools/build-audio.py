#!/usr/bin/env python3
"""Write data/audio-manifest.js: which texts have a recording in audio/, so the site plays them instead of the browser voice.

Files made by tools/make-audio.py (the Qwen voice) are listed in audio/index.json (key -> file name) and named
<first 14 hex digits of sha1(key)>.mp3; a key starting with "m|" is the man's voice. The site works such a file's name out from the
text itself (audiolist.js), so the manifest only lists the first W hex digits of each key's SHA-1, sorted and joined into one string
(window.SHANLU_AUDIO_IDS). That is about 150 KB instead of a 1 MB text -> file list.
Any other file (named like the text it speaks, 你好.mp3, or a made file whose name is not its key's hash) goes in window.SHANLU_AUDIO
(text -> extension, or the file name itself when it has a dot), as before.
The site matches the text exactly as shown on screen, so a word or sentence that is written differently in the 儿 style needs its own file.
Run:  python3 tools/build-audio.py
"""
import hashlib, json, os, sys, unicodedata
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import audiostore   # B4: the recordings may live in a Cloudflare R2 bucket (audio/r2.json)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO = os.path.join(ROOT, 'audio')
EXT = ('.mp3', '.m4a', '.ogg', '.wav', '.webm')
RANK = {e: i for i, e in enumerate(EXT)}      # when one text has several files, the first extension in this list wins
W = 7                                          # hex digits per key in the list: the same W as in audiolist.js


def main():
    other = {}
    idx = os.path.join(AUDIO, 'index.json')
    made = json.load(open(idx, encoding='utf-8')) if os.path.exists(idx) else {}
    madefiles = set(made.values())
    for name in sorted(os.listdir(AUDIO)) if os.path.isdir(AUDIO) else []:
        if name in madefiles:
            continue
        stem, ext = os.path.splitext(unicodedata.normalize('NFC', name))
        if ext.lower() not in EXT:
            continue
        if stem not in other or RANK[ext.lower()] < RANK['.' + other[stem]]:
            other[stem] = ext.lower()[1:]
    ids = set()
    for text, file in made.items():
        if not audiostore.have(file):
            continue
        key = unicodedata.normalize('NFC', text)
        h = hashlib.sha1(key.encode('utf-8')).hexdigest()
        if file == h[:14] + '.mp3':
            ids.add(h[:W])
        else:
            other[key] = file
    with open(os.path.join(ROOT, 'data', 'audio-manifest.js'), 'w', encoding='utf-8') as f:
        f.write('/* Recorded audio for Shanlu. GENERATED by tools/build-audio.py from the files in audio/. Do not edit by hand.\n')
        f.write(' * SHANLU_AUDIO_IDS: the first %d hex digits of sha1(key) of every recording named by its hash, sorted (audiolist.js reads it).\n' % W)
        f.write(' * SHANLU_AUDIO: any other recording, key -> extension (audio/<text>.<ext>) or file name. A key starting with m| is the man voice. */\n')
        f.write('window.SHANLU_AUDIO_IDS = "' + ''.join(sorted(ids)) + '";\n')
        f.write('window.SHANLU_AUDIO = ' + json.dumps(other, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n')
        r = audiostore.remote()
        if r:   # the recordings are played from the R2 bucket (audiolist.js puts this in front of audio/<file>)
            f.write('window.SHANLU_AUDIO_BASE = ' + json.dumps(r['base']) + ';\n')
    print('wrote data/audio-manifest.js: %d recordings (%d listed by hash, %d by name)' % (len(ids) + len(other), len(ids), len(other)))


if __name__ == '__main__':
    sys.exit(main())
