#!/usr/bin/env python3
"""Build data/hsk1-words.js from the hand-written word files in content/.

Authoring files (tab separated):  zh, part of speech, English gloss, example sentence, example English.
Pinyin is NOT typed by hand. It is generated here from pypinyin plus content/pinyin-overrides.tsv (neutral tones,
erhua, words the library gets wrong) and the tone-change rules for 不 and 一. Each sentence is also split into words
using only the HSK 1 list, so the app can build "put the words in order" questions.

Run:  python3 tools/build-words.py
Needs: pip install pypinyin jieba
"""
import glob, json, os, re, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pinyin_engine import Engine

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content')

NAMES = ['小明']                       # names allowed in example sentences
PUNCT = '，。？！、：；“”（）…'
P_MAP = {'，': ',', '。': '.', '？': '?', '！': '!', '、': ',', '：': ':', '；': ';', '“': '"', '”': '"', '（': '(', '）': ')', '…': '...'}
NUMBER_PREV = '第月期十二三四五六七八九零'
DIGITS = '二三四五六七八九'
NUM_CHARS = '一二两三四五六七八九十百千零'
PROPER = {'中国', '汉语', '中文', '小明'}     # capitalised in pinyin
ATTACH = {'们'}                              # suffix written together with the word before it

TONES = {'ā': 1, 'ē': 1, 'ī': 1, 'ō': 1, 'ū': 1, 'ǖ': 1, 'á': 2, 'é': 2, 'í': 2, 'ó': 2, 'ú': 2, 'ǘ': 2,
         'ǎ': 3, 'ě': 3, 'ǐ': 3, 'ǒ': 3, 'ǔ': 3, 'ǚ': 3, 'à': 4, 'è': 4, 'ì': 4, 'ò': 4, 'ù': 4, 'ǜ': 4}


def tone_of(syl):
    for ch in syl:
        if ch in TONES:
            return TONES[ch]
    return 0


def read_tsv(path):
    rows = []
    with open(path, encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line.strip():
                continue
            rows.append((n, line.split('\t')))
    return rows


def main():
    official = [l.strip() for l in open(os.path.join(C, 'hsk1-official-300.txt'), encoding='utf-8') if l.strip()]

    words = []
    for path in sorted(glob.glob(os.path.join(C, 'words-*.tsv'))):
        for n, p in read_tsv(path):
            if len(p) not in (5, 6) or any(not x.strip() for x in p[:5]):
                sys.exit('%s line %d: expected 5 filled columns plus an optional note, got %r' % (os.path.basename(path), n, p))
            words.append(dict(zh=p[0], pos=p[1], en=p[2], ex_zh=p[3], ex_en=p[4], note=(p[5].strip() if len(p) > 5 else '')))

    have = [w['zh'] for w in words]
    missing = [w for w in official if w not in have]
    extra = [w for w in have if w not in official]
    dups = sorted({w for w in have if have.count(w) > 1})
    if missing or extra or dups:
        sys.exit('word list does not match the official 300: missing=%s extra=%s dups=%s' % (missing, extra, dups))

    eng = Engine(official)
    lines = []
    for w in words:
        w['py'] = eng.word_py(w['zh'])
        py, toks = eng.sentence(w['ex_zh'])
        ex = dict(zh=w['ex_zh'], py=py, en=w['ex_en'], toks=toks)
        entry = dict(zh=w['zh'], py=w['py'], pos=w['pos'], en=w['en'], ex=ex)
        if w['note']:
            entry['note'] = w['note']
        lines.append(json.dumps(entry, ensure_ascii=False))

    out_path = os.path.join(ROOT, 'data', 'hsk1-words.js')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('/* HSK 1 words for Shanlu. GENERATED by tools/build-words.py from content/words-*.tsv. Do not edit by hand.\n')
        f.write(' * Word list: the 300 words of the November 2025 HSK 3.0 exam syllabus, band 1 (see content/hsk1-official-300.txt).\n')
        f.write(' * Status: glosses and example sentences were written and checked by AI (see CONTENT-CHECKS.md). They have NOT been reviewed by a human teacher. */\n')
        f.write('window.HSK1_WORDS = [\n' + ',\n'.join(lines) + '\n];\n')
    print('wrote %s (%d words)' % (out_path, len(lines)))


if __name__ == '__main__':
    main()
