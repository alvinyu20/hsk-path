#!/usr/bin/env python3
"""Build data/hsk2-preview.js from content/preview-hsk2.tsv.

The AI conversation may use a few HSK 2 words as a preview. The learner is shown their pinyin and English, so the pinyin must be right:
every entry is checked against the dataset (the word must be an HSK 2 word of the 2025 syllabus, and the syllables must match one of the
dataset's readings once tone marks are ignored). Every HSK 2 word in the dataset must be listed, so none is missing.

Run:  python3 tools/build-preview.py /path/to/complete.json
"""
import json, os, re, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def toneless(py):
    s = unicodedata.normalize('NFD', py)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    return re.sub(r"[\s'/-]", '', s).lower().replace('ü', 'u')


def main():
    dataset = sys.argv[1] if len(sys.argv) > 1 else None
    rows = []
    for ln, line in enumerate(open(os.path.join(ROOT, 'content', 'preview-hsk2.tsv'), encoding='utf-8'), 1):
        if line.startswith('#') or not line.strip():
            continue
        p = line.rstrip('\n').split('\t')
        if len(p) != 3 or not all(p):
            sys.exit('build-preview: line %d needs word, pinyin, English' % ln)
        rows.append(p)
    zhs = [r[0] for r in rows]
    if len(zhs) != len(set(zhs)):
        sys.exit('build-preview: duplicate words: %s' % sorted({z for z in zhs if zhs.count(z) > 1}))
    off = {l.strip() for l in open(os.path.join(ROOT, 'content', 'hsk1-official-300.txt'), encoding='utf-8') if l.strip()}
    for z in zhs:
        if z in off:
            sys.exit('build-preview: %s is an HSK 1 word already' % z)
    if dataset and os.path.exists(dataset):
        data = json.load(open(dataset, encoding='utf-8'))
        by = {}
        for w in data:
            by.setdefault(w['simplified'], []).append(w)
        lvl2 = {w['simplified'] for w in data if 'newest-2' in w['level'] and 'newest-1' not in w['level']}
        # plain forms of the 儿 words are listed too; they belong to the same HSK 2 word
        extra_ok = {z[:-1] for z in zhs if z.endswith('儿')}
        for z, py, en in rows:
            if z not in by and z in extra_ok:
                continue
            if z not in by:
                sys.exit('build-preview: %s is not in the dataset' % z)
            if z not in lvl2 and z not in extra_ok:
                sys.exit('build-preview: %s is not an HSK 2 word of the newest syllabus' % z)
            readings = {toneless(f['transcriptions']['pinyin']) for w in by[z] for f in w['forms']}
            if toneless(py) not in readings:
                sys.exit('build-preview: pinyin of %s (%s) does not match the dataset (%s)' % (z, py, sorted(readings)))
        missing = sorted(lvl2 - set(zhs) - {z for z in lvl2 if z + '儿' in zhs})
        if missing:
            sys.exit('build-preview: HSK 2 words missing from the list: %s' % ' '.join(missing))
        print('checked against the dataset: %d HSK 2 words, none missing' % len(lvl2))
    out = {z: [py, en] for z, py, en in rows}
    path = os.path.join(ROOT, 'data', 'hsk2-preview.js')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('/* HSK 2 preview words for the AI conversation. GENERATED by tools/build-preview.py from content/preview-hsk2.tsv. Do not edit by hand.\n')
        f.write(' * Pinyin is checked against the HSK dataset; the English glosses were written by AI and have NOT been reviewed by a teacher. */\n')
        f.write('window.HSK2_PREVIEW = ' + json.dumps(out, ensure_ascii=False) + ';\n')
    print('wrote %s: %d preview words' % (path, len(out)))


if __name__ == '__main__':
    main()
