#!/usr/bin/env python3
"""Build data/hsk2-preview.js from content/preview-hsk2.tsv.

The AI conversation may use a few HSK 2 words as a preview. The learner is shown their pinyin and English, so the pinyin must be right:
every entry is checked against the dataset (the word must be an HSK 2 word of the 2025 syllabus, and the syllables must match one of the
dataset's readings once tone marks are ignored). Every HSK 2 word in the dataset must be listed, so none is missing.

Run:  python3 tools/build-preview.py /path/to/complete.json
"""
import json, os, re, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def toneless(py):
    s = unicodedata.normalize('NFD', py)
    s = ''.join(c for c in s if not unicodedata.combining(c))
    return re.sub(r"[\s'/-]", '', s).lower().replace('ü', 'u')


def main():
    dataset = sys.argv[1] if len(sys.argv) > 1 else None
    level = int(sys.argv[2]) if len(sys.argv) > 2 else 2   # the level being previewed: 2 (used at HSK 1) or 3 (used at HSK 2)
    rows = []
    for ln, line in enumerate(open(os.path.join(ROOT, 'content', 'preview-hsk%d.tsv' % level), encoding='utf-8'), 1):
        if line.startswith('#') or not line.strip():
            continue
        p = line.rstrip('\n').split('\t')
        if len(p) != 3 or not all(p):
            sys.exit('build-preview: line %d needs word, pinyin, English' % ln)
        rows.append(p)
    zhs = [r[0] for r in rows]
    if len(zhs) != len(set(zhs)):
        sys.exit('build-preview: duplicate words: %s' % sorted({z for z in zhs if zhs.count(z) > 1}))
    # a preview word must be a word the learner has not met yet: not on the site's lists for this level or below
    own = set()
    for f in ['hsk1-official-300.txt', 'hsk2-official-197.txt'][:level - 1]:
        own |= {l.strip() for l in open(os.path.join(ROOT, 'content', f), encoding='utf-8') if l.strip()}
    for z in zhs:
        if z in own:
            sys.exit('build-preview: %s is already a word of level %d or below' % (z, level - 1))
    if dataset and os.path.exists(dataset):
        data = json.load(open(dataset, encoding='utf-8'))
        by = {}
        for w in data:
            by.setdefault(w['simplified'], []).append(w)
        tag = 'newest-%d' % level
        newer = ['newest-%d' % n for n in range(1, level)]
        lvl = {w['simplified'] for w in data if tag in w['level'] and not any(t in w['level'] for t in newer)}
        # plain forms of the 儿 words are listed too; they belong to the same word
        extra_ok = {z[:-1] for z in zhs if z.endswith('儿')} | {z + '儿' for z in zhs if z + '儿' in lvl}
        for z, py, en in rows:
            if z not in by and z in extra_ok:
                continue
            if z not in by:
                sys.exit('build-preview: %s is not in the dataset' % z)
            if z not in lvl and z not in extra_ok:
                sys.exit('build-preview: %s is not an HSK %d word of the newest syllabus' % (z, level))
            readings = {toneless(f['transcriptions']['pinyin']) for w in by[z] for f in w['forms']}
            if toneless(py) not in readings:
                sys.exit('build-preview: pinyin of %s (%s) does not match the dataset (%s)' % (z, py, sorted(readings)))
        missing = sorted(lvl - set(zhs) - {z for z in lvl if z + '儿' in zhs})
        if level == 2 and missing:
            sys.exit('build-preview: HSK 2 words missing from the list: %s' % ' '.join(missing))
        print('checked against the dataset: %d HSK %d words in the dataset, %d listed%s' % (len(lvl), level, len(zhs), (', %d left out on purpose' % len(missing)) if missing else ''))
    out = {z: [py, en] for z, py, en in rows}
    path = os.path.join(ROOT, 'data', 'hsk%d-preview.js' % level)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('/* HSK %d preview words for the AI conversation. GENERATED by tools/build-preview.py from content/preview-hsk%d.tsv. Do not edit by hand.\n' % (level, level))
        f.write(' * Pinyin is checked against the HSK dataset; the English glosses were written by AI and have NOT been reviewed by a teacher. */\n')
        f.write('window.HSK%d_PREVIEW = ' % level + json.dumps(out, ensure_ascii=False) + ';\n')
    print('wrote %s: %d preview words' % (path, len(out)))


if __name__ == '__main__':
    main()
