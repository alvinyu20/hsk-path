#!/usr/bin/env python3
"""Build data/char-glosses.js from content/char-glosses.tsv (char<TAB>short meaning).
The "Built from" chips use it for a character that is not a word of its own at the learner's level.
Run:  python3 tools/build-char-glosses.py [--check]"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, 'content', 'char-glosses.tsv')
out = os.path.join(ROOT, 'data', 'char-glosses.js')
g = {}
for n, line in enumerate(open(src, encoding='utf-8'), 1):
    line = line.rstrip('\n')
    if not line.strip() or line.startswith('#'):
        continue
    p = line.split('\t')
    if len(p) != 2 or len(p[0]) != 1 or not p[1].strip():
        sys.exit('build-char-glosses: line %d should be one character, a tab, and a meaning: %r' % (n, line))
    if p[0] in g:
        sys.exit('build-char-glosses: %s is listed twice' % p[0])
    g[p[0]] = p[1].strip()
text = ('/* Short meanings for single characters. GENERATED by tools/build-char-glosses.py from content/char-glosses.tsv. Do not edit by hand.\n'
        ' * Written by AI. NOT reviewed by a human teacher. */\n'
        'window.CHAR_GLOSSES = ' + json.dumps(g, ensure_ascii=False, indent=0, sort_keys=True).replace('\n', '') + ';\n')
if '--check' in sys.argv:
    if not os.path.exists(out) or open(out, encoding='utf-8').read() != text:
        sys.exit('build-char-glosses: data/char-glosses.js is out of date (run python3 tools/build-char-glosses.py)')
    print('char glosses are current (%d)' % len(g))
else:
    open(out, 'w', encoding='utf-8').write(text)
    print('wrote data/char-glosses.js (%d characters)' % len(g))
