#!/usr/bin/env python3
"""Write data/confusers.js: the tables the app uses for smarter wrong answers (D4).

  look: groups of look-alike characters (content/look-alikes.tsv), only characters that are in an HSK 1-5 word
  same: groups of words that mean the same (content/same-meaning-groups.tsv): never offered side by side where you pick the Chinese word,
        because both would be right

The app finds the rest itself from the loaded words: words that differ only in look-alike characters, words that share a character
(饭店 / 商店), words that differ only in tone (买 mǎi / 卖 mài), opposites and topic partners from the word webs.
Run:  python3 tools/build-confusers.py        (--check: exit 1 if data/confusers.js is out of date)
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content')


def level_words():
    """Every word of HSK 1-5 from data/levels-index.js (written by tools/build-site.js)."""
    src = open(os.path.join(ROOT, 'data', 'levels-index.js'), encoding='utf-8').read()
    idx = json.loads(src[src.index('window.SHANLU_INDEX = ') + len('window.SHANLU_INDEX = '):].rstrip().rstrip(';'))
    return {w[0] for lv in idx.values() for w in lv['w']}


def main():
    words = level_words()
    chars = {ch for w in words for ch in w}
    look, seen = [], set()
    for n, line in enumerate(open(os.path.join(C, 'look-alikes.tsv'), encoding='utf-8'), 1):
        if line.startswith('#') or not line.strip():
            continue
        group = line.split('\t')[0].split()
        if len(set(group)) != len(group):
            sys.exit('content/look-alikes.tsv line %d repeats a character' % n)
        kept = ''.join(ch for ch in group if ch in chars)
        if len(kept) >= 2 and kept not in seen:
            seen.add(kept)
            look.append(kept)
    same = []
    for line in open(os.path.join(C, 'same-meaning-groups.tsv'), encoding='utf-8'):
        if line.startswith('#') or not line.strip():
            continue
        g = [w for w in line.rstrip('\n').split('\t')[1].split() if w]
        if len(g) >= 2:
            same.append(g)
    out = ('/* GENERATED by tools/build-confusers.py from content/look-alikes.tsv and content/same-meaning-groups.tsv. Do not edit by hand.\n'
           ' * look: look-alike characters (one string per group). same: words that mean the same (never wrong answers for each other). */\n'
           'window.SHANLU_CONFUSERS = ' + json.dumps({'look': look, 'same': same}, ensure_ascii=False, separators=(',', ':')) + ';\n')
    path = os.path.join(ROOT, 'data', 'confusers.js')
    if '--check' in sys.argv:
        if not os.path.exists(path) or open(path, encoding='utf-8').read() != out:
            sys.exit('data/confusers.js is out of date: run python3 tools/build-confusers.py')
        print('data/confusers.js is up to date (%d look-alike groups, %d same-meaning groups)' % (len(look), len(same)))
        return
    open(path, 'w', encoding='utf-8').write(out)
    print('wrote data/confusers.js: %d look-alike groups, %d same-meaning groups' % (len(look), len(same)))


if __name__ == '__main__':
    main()
