#!/usr/bin/env python3
"""Build data/hsk1-speak.js (practice scripts) and data/hsk1-listen.js (listening clips) from content/speaking.json
and content/listening.json. Pinyin, word splits and dictation keys are generated.
Run:  python3 tools/build-speech.py
"""
import json, os, re, sys, unicodedata
from pypinyin import lazy_pinyin, Style
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pinyin_engine import Engine
import levelcfg

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content')


def toneless(py):
    s = unicodedata.normalize('NFD', py)
    return re.sub(r"[^a-z]", '', ''.join(c for c in s if not unicodedata.combining(c)).lower())


MARKS = {'\u0304': 1, '\u0301': 2, '\u030c': 3, '\u0300': 4}


def tone_pair(zh, py):
    """The tones of a two-character word, read from the pinyin the site shows (so the neutral tones set by hand count).
    Returns [t1, t2] with 1-4 for the four tones and 5 for the light (neutral) tone, or None when it is not clear."""
    letters = []
    for ch in unicodedata.normalize('NFD', py.lower()):
        if ch in MARKS:
            if not letters:
                return None
            letters[-1][1] = MARKS[ch]
        elif unicodedata.combining(ch):
            continue
        elif ch.isalpha():
            letters.append([ch, 0])
    n1 = len(re.sub('[^a-z\u00fc]', '', lazy_pinyin(zh[0], style=Style.NORMAL)[0]))
    n2 = len(re.sub('[^a-z\u00fc]', '', lazy_pinyin(zh[1], style=Style.NORMAL)[0]))
    if n1 + n2 != len(letters) or n1 == 0 or n2 == 0:
        return None
    def tone(seg):
        t = max(x[1] for x in seg)
        return t if t else 5
    t1 = tone(letters[:n1])
    if t1 == 5:
        return None                      # a word that starts with a light syllable cannot be a pair to listen for
    return [t1, tone(letters[n1:])]


def die(m):
    sys.exit('build-speech: ' + m)


def lower_first(py):
    return py[:1].lower() + py[1:]


def main():
    LV = levelcfg.LEVEL
    eng = Engine(levelcfg.known())

    sp = json.load(open(os.path.join(levelcfg.CONTENT, 'speaking.json'), encoding='utf-8'))
    scenarios = []
    for s in sp['scenarios']:
        if len(s['ai']) != len(s['you']) + 1:
            die('scenario %s: needs one more speaker line than your lines' % s['id'])
        if len(s['goals']) != len(s['you']):
            die('scenario %s: one goal per line of yours' % s['id'])
        def conv(lines):
            return [dict(zh=l['zh'], py=eng.sentence(l['zh'])[0], en=l['en']) for l in lines]
        words = [dict(zh=w, py=lower_first(eng.sentence(w)[0])) for w in s['words']]
        scenarios.append(dict(id=s['id'], glyph=s['glyph'], title=s['title'], sub=s['sub'], goals=s['goals'], words=words, ai=conv(s['ai']), you=conv(s['you'])))
    phrases = [dict(zh=p['zh'], py=eng.sentence(p['zh'])[0], en=p['en']) for p in sp['phrases']]

    li = json.load(open(os.path.join(levelcfg.CONTENT, 'listening.json'), encoding='utf-8'))
    clips = []
    for c in li['clips']:
        py, toks = eng.sentence(c['zh'])
        def reading(t):
            # a word with several readings ("guo / guò") shows the one this sentence uses
            alts = eng.word_py(t).split(' / ')
            return next((a for a in alts if a in py.lower()), alts[0])
        words = [dict(zh=t, py=reading(t), key=toneless(reading(t))) for t in toks]
        clips.append(dict(zh=c['zh'], py=py, en=c['en'], words=words, notes=c.get('notes', [])))
    tones = li['tones']

    # two-syllable words for the tone-pair trainer: every two-character word of this level and the levels before it
    # (not words with 不 or 一, whose tone changes, nor 儿 words)
    pairs = []
    for z in levelcfg.known():
        if len(z) != 2 or re.search('[\u4e0d\u4e00\u513f]', z):
            continue
        py = eng.word_py(z)
        if not py or '/' in py or ' ' in py:
            continue
        t = tone_pair(z, py)
        if t:
            pairs.append(dict(zh=z, t=t))

    print('tone pairs: %d two-syllable words' % len(pairs))
    with open(levelcfg.data_path('speak'), 'w', encoding='utf-8') as f:
        f.write('/* HSK %d speaking practice scripts for Shanlu. GENERATED by tools/build-speech.py from the speaking.json of this level. Do not edit by hand.\n' % LV)
        f.write(' * These are fixed scripts you say out loud yourself. There is no speech recognition or feedback yet. AI-written, not reviewed by a human teacher. */\n')
        f.write('window.HSK%d_SPEAK = ' % LV + json.dumps(dict(scenarios=scenarios, phrases=phrases), ensure_ascii=False, indent=1) + ';\n')
    with open(levelcfg.data_path('listen'), 'w', encoding='utf-8') as f:
        f.write('/* HSK %d listening clips for Shanlu. GENERATED by tools/build-speech.py from the listening.json of this level. Do not edit by hand.\n' % LV)
        f.write(' * Clips are read aloud by the browser\'s own voice. The "what to listen for" notes are AI-written and not reviewed by a human teacher. */\n')
        f.write('window.HSK%d_LISTEN = ' % LV + json.dumps(dict(clips=clips, tones=tones, pairs=pairs), ensure_ascii=False, indent=1) + ';\n')
    print('wrote data/hsk%d-speak.js (%d scenarios) and data/hsk%d-listen.js (%d clips)' % (LV, len(scenarios), LV, len(clips)))


if __name__ == '__main__':
    main()
