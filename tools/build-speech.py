#!/usr/bin/env python3
"""Build data/hsk1-speak.js (practice scripts) and data/hsk1-listen.js (listening clips) from content/speaking.json
and content/listening.json. Pinyin, word splits and dictation keys are generated.
Run:  python3 tools/build-speech.py
"""
import json, os, re, sys, unicodedata
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pinyin_engine import Engine

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content')


def toneless(py):
    s = unicodedata.normalize('NFD', py)
    return re.sub(r"[^a-z]", '', ''.join(c for c in s if not unicodedata.combining(c)).lower())


def die(m):
    sys.exit('build-speech: ' + m)


def lower_first(py):
    return py[:1].lower() + py[1:]


def main():
    official = [l.strip() for l in open(os.path.join(C, 'hsk1-official-300.txt'), encoding='utf-8') if l.strip()]
    eng = Engine(official)

    sp = json.load(open(os.path.join(C, 'speaking.json'), encoding='utf-8'))
    scenarios = []
    for s in sp['scenarios']:
        if len(s['ai']) != len(s['you']) + 1:
            die('scenario %s: needs one more speaker line than your lines' % s['id'])
        if len(s['goals']) != len(s['you']):
            die('scenario %s: one goal per line of yours' % s['id'])
        def conv(lines):
            return [dict(zh=l['zh'], py=eng.sentence(l['zh'])[0], en=l['en']) for l in lines]
        words = [dict(zh=w, py=lower_first(eng.sentence(w)[0])) for w in s['words']]
        scenarios.append(dict(id=s['id'], glyph=s['glyph'], title=s['title'], sub=s['sub'], goals=s['goals'], words=words, ai=conv(s['ai']), you=conv(s['you'])))
    phrases = [dict(zh=p['zh'], py=eng.sentence(p['zh'])[0], en=p['en']) for p in sp['phrases']]

    li = json.load(open(os.path.join(C, 'listening.json'), encoding='utf-8'))
    clips = []
    for c in li['clips']:
        py, toks = eng.sentence(c['zh'])
        words = [dict(zh=t, py=eng.word_py(t), key=toneless(eng.word_py(t))) for t in toks]
        clips.append(dict(zh=c['zh'], py=py, en=c['en'], words=words, notes=c.get('notes', [])))
    tones = li['tones']

    with open(os.path.join(ROOT, 'data', 'hsk1-speak.js'), 'w', encoding='utf-8') as f:
        f.write('/* HSK 1 speaking practice scripts for Shanlu. GENERATED by tools/build-speech.py from content/speaking.json. Do not edit by hand.\n')
        f.write(' * These are fixed scripts you say out loud yourself. There is no speech recognition or feedback yet. AI-written, not reviewed by a human teacher. */\n')
        f.write('window.HSK1_SPEAK = ' + json.dumps(dict(scenarios=scenarios, phrases=phrases), ensure_ascii=False, indent=1) + ';\n')
    with open(os.path.join(ROOT, 'data', 'hsk1-listen.js'), 'w', encoding='utf-8') as f:
        f.write('/* HSK 1 listening clips for Shanlu. GENERATED by tools/build-speech.py from content/listening.json. Do not edit by hand.\n')
        f.write(' * Clips are read aloud by the browser\'s own voice. The "what to listen for" notes are AI-written and not reviewed by a human teacher. */\n')
        f.write('window.HSK1_LISTEN = ' + json.dumps(dict(clips=clips, tones=tones), ensure_ascii=False, indent=1) + ';\n')
    print('wrote data/hsk1-speak.js (%d scenarios) and data/hsk1-listen.js (%d clips)' % (len(scenarios), len(clips)))


if __name__ == '__main__':
    main()
