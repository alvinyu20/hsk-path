#!/usr/bin/env python3
"""Writes data/pinyin-chart.js: the sound chart of the pinyin course ("Pinyin" screen, Learn).

For every syllable + tone that occurs in the HSK 1-3 word lists it picks ONE real character to say aloud, so the person can tap a syllable and hear it.
The character must (a) be written in an HSK 1-3 word and (b) have exactly one reading in pypinyin's dictionary
(so the browser voice cannot choose a different reading). Single-character HSK words come first, then HSK 1 words, then HSK 2, then HSK 3.
Nothing here is typed by hand: syllables come from pypinyin, glosses from the word files.

Run:  python3 tools/build-pinyin-chart.py        Needs: pip install pypinyin
"""
import json, os, re, sys
from pypinyin import pinyin, Style

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def words(level):
    out = []
    with open(os.path.join(ROOT, 'data', 'hsk%d-words.js' % level), encoding='utf-8') as f:
        for line in f:
            line = line.strip().rstrip(',')
            if line.startswith('{"zh"'):
                out.append(json.loads(line))
    return out


def readings(ch):
    r = pinyin(ch, style=Style.TONE3, heteronym=True, neutral_tone_with_five=True)
    return sorted(set(x for x in r[0]))


def short_gloss(en):
    g = re.split(r'[;(]', en)[0]
    g = g.split(',')[0].strip()
    return g


def main():
    cand = {}   # 'ba1' -> list of (rank, zh, word, gloss)
    for lv in (1, 2, 3):
        for w in words(lv):
            zh, en = w['zh'], short_gloss(w['en'])
            for ch in set(zh):
                if not '一' <= ch <= '鿿':
                    continue
                rd = readings(ch)
                if len(rd) != 1:
                    continue
                syl = rd[0]
                if not re.search(r'[1-4]$', syl):
                    continue   # no neutral-tone entries
                solo = (zh == ch)
                rank = (0 if solo else 1, lv)
                cand.setdefault(syl, []).append((rank, ch, zh, en))
    chart = {}
    for syl, lst in cand.items():
        lst.sort(key=lambda x: (x[0], x[1]))
        rank, ch, zh, en = lst[0]
        chart[syl] = {'c': ch, 'w': zh if zh != ch else '', 'e': en}
    keys = sorted(chart, key=lambda s: (s[:-1], s[-1]))
    out = os.path.join(ROOT, 'data', 'pinyin-chart.js')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* Sound chart for the pinyin course. GENERATED by tools/build-pinyin-chart.py. Do not edit by hand.\n')
        f.write(' * One real character per syllable and tone, taken from the HSK 1-3 word lists; only characters with a single reading are used.\n')
        f.write(' * Keys are pinyin with tone numbers (ba1, lv4: v is u-umlaut). c = character, w = the HSK word it comes from (empty if the character is a word itself), e = English. */\n')
        f.write('window.SHANLU_PYCHART = {\n')
        f.write(',\n'.join('%s: %s' % (json.dumps(k), json.dumps(chart[k], ensure_ascii=False)) for k in keys))
        f.write('\n};\n')
    sy = set(k[:-1] for k in keys)
    print('chart: %d syllable+tone entries, %d syllables' % (len(keys), len(sy)))


if __name__ == '__main__':
    main()
