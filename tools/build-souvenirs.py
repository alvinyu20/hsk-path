#!/usr/bin/env python3
"""Builds data/souvenirs.js from content/souvenirs.tsv and content/souvenir-art.json.

  node tools/souvenir-art.js            (pictures -> content/souvenir-art.json)
  python3 tools/build-souvenirs.py      (this: checks every souvenir and writes data/souvenirs.js)

A souvenir is hidden in one stop of the Journey and is found when that stop is unlocked. This checks that the stop exists (and is the
kind named), that no stop hides two souvenirs, that every souvenir has a picture, and makes the pinyin (unless the line gives it).
Use --partial while pictures are still being drawn: souvenirs without a picture are left out and listed.
"""
import json, os, re, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
partial = '--partial' in sys.argv


def slug(s):
    s = unicodedata.normalize('NFD', str(s).lower())
    s = ''.join(c for c in s if not unicodedata.combining(c))
    return re.sub(r'^-|-$', '', re.sub(r'[^a-z0-9]+', '-', s))


def load_stops():
    """The stop ids exactly as journey.js makes them: region.slug(kind + ' ' + english name), with -2, -3 for repeats in a region."""
    txt = open(os.path.join(ROOT, 'data', 'journey.js'), encoding='utf-8').read()
    data = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
    stops = {}   # id -> (kind, en)
    for r in data['regions']:
        used = {}
        for c in r['cities']:
            for s in c['stops']:
                kind, en = s[0], s[3]
                sid = r['id'] + '.' + slug(kind + ' ' + en)
                if sid in used:
                    k = 2
                    while (sid + '-' + str(k)) in used:
                        k += 1
                    sid += '-' + str(k)
                used[sid] = 1
                stops[sid] = (kind, en)
    return stops


def make_pinyin(zh):
    from pypinyin import pinyin, Style
    import jieba, logging
    jieba.setLogLevel(logging.WARNING)
    words = [w for w in jieba.lcut(zh) if w.strip()]
    out = []
    for w in words:
        syl = [x[0] for x in pinyin(w, style=Style.TONE, heteronym=False)]
        txt = syl[0]
        for x in syl[1:]:
            txt += ('\u2019' if x[0] in 'aāáǎàoōóǒòeēéěè' else '') + x   # wán’ǒu: an apostrophe keeps the syllables apart
        out.append(txt)
    return ' '.join(out)


def main():
    stops = load_stops()
    art = json.load(open(os.path.join(ROOT, 'content', 'souvenir-art.json'), encoding='utf-8'))
    items, problems, skipped, used_stop, seen_id = [], [], [], {}, {}
    for n, ln in enumerate(open(os.path.join(ROOT, 'content', 'souvenirs.tsv'), encoding='utf-8'), 1):
        ln = ln.rstrip('\n')
        if not ln.strip() or ln.startswith('#'):
            continue
        f = ln.split('\t')
        if len(f) < 7:
            problems.append('line %d: needs at least 7 fields, has %d' % (n, len(f))); continue
        sid, rid, kind, stop_en, zh, en, story = [x.strip() for x in f[:7]]
        py = f[7].strip() if len(f) > 7 and f[7].strip() else ''
        if sid in seen_id:
            problems.append('line %d: duplicate id %s' % (n, sid))
        seen_id[sid] = 1
        stop_id = rid + '.' + slug(kind + ' ' + stop_en)
        if stop_id not in stops:
            problems.append('line %d (%s): there is no stop %s' % (n, sid, stop_id)); continue
        if stops[stop_id][1] != stop_en or stops[stop_id][0] != kind:
            problems.append('line %d (%s): stop %s does not match (%s)' % (n, sid, stop_id, stops[stop_id]))
        if stop_id in used_stop:
            problems.append('line %d (%s): stop %s already hides %s' % (n, sid, stop_id, used_stop[stop_id]))
        used_stop[stop_id] = sid
        if not re.search(r'[一-鿿]', zh):
            problems.append('line %d (%s): the Chinese name has no Chinese characters' % (n, sid))
        if len(story) > 260:
            problems.append('line %d (%s): the story is %d characters, keep it under 260' % (n, sid, len(story)))
        if sid not in art:
            if partial:
                skipped.append(sid); continue
            problems.append('line %d (%s): no picture in content/souvenir-art.json' % (n, sid)); continue
        items.append({'id': sid, 'stop': stop_id, 'rid': rid, 'zh': zh, 'py': py or make_pinyin(zh), 'en': en, 'story': story, 'svg': art[sid]})
    unused = [k for k in art if k not in seen_id]
    if unused:
        problems.append('pictures with no souvenir line: ' + ', '.join(unused))
    if problems:
        print('PROBLEMS:'); print('\n'.join(problems)); sys.exit(1)
    # the shelf follows the order of the lines in the content file
    out = '/* GENERATED by tools/build-souvenirs.py from content/souvenirs.tsv and content/souvenir-art.json. Do not edit by hand. */\nwindow.SOUVENIRS = ' + json.dumps(items, ensure_ascii=False, separators=(',', ':')) + ';\n'
    open(os.path.join(ROOT, 'data', 'souvenirs.js'), 'w', encoding='utf-8').write(out)
    print('wrote %d souvenirs to data/souvenirs.js (%d KB)' % (len(items), len(out) // 1024) + (('; left out, no picture yet: ' + ', '.join(skipped)) if skipped else ''))
    if '--show' in sys.argv:
        for it in items:
            print(it['id'].ljust(22), it['zh'].ljust(10), it['py'])


main()
