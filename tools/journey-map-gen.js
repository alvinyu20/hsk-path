/* Builds data/journey-map.js (map outlines for the Journey). Run from a folder with d3-geo and @turf/simplify installed:
 *   node mapgen.js admin1.geojson data/journey-map.js
 * Source: Natural Earth admin-1 (public domain), ne_10m_admin_1_states_provinces. */
const fs = require('fs');
const d3 = require('d3-geo');
const simplify = require('@turf/simplify').default || require('@turf/simplify');
const g = JSON.parse(fs.readFileSync(process.argv[2] || '/tmp/geo/admin1.geojson'));
const F = g.features;
const P = (f) => f.properties;
const simp = (feat, tol) => simplify(JSON.parse(JSON.stringify(feat)), { tolerance: tol, highQuality: false, mutate: true });

// region id -> Natural Earth selectors
const MAIN = { anhui: 'Anhui', fujian: 'Fujian', gansu: 'Gansu', guangdong: 'Guangdong', guangxi: 'Guangxi', guizhou: 'Guizhou', hainan: 'Hainan', hebei: 'Hebei', heilongjiang: 'Heilongjiang', henan: 'Henan', hubei: 'Hubei', hunan: 'Hunan', neimenggu: 'Inner Mongol', jiangsu: 'Jiangsu', jiangxi: 'Jiangxi', jilin: 'Jilin', liaoning: 'Liaoning', ningxia: 'Ningxia', qinghai: 'Qinghai', shaanxi: 'Shaanxi', shandong: 'Shandong', shanxi: 'Shanxi', sichuan: 'Sichuan', xinjiang: 'Xinjiang', xizang: 'Xizang', yunnan: 'Yunnan', zhejiang: 'Zhejiang' };
const MUNI = { hebei: ['Beijing', 'Tianjin'], jiangsu: ['Shanghai'], sichuan: ['Chongqing'] };
const china = F.filter((f) => P(f).admin === 'China');
const byName = (n) => china.filter((f) => P(f).name === n);
const tw = F.filter((f) => P(f).admin === 'Taiwan');
const hk = F.filter((f) => /Hong Kong/.test(P(f).admin));
const mo = F.filter((f) => /Macau/.test(P(f).admin));
const sg = F.filter((f) => P(f).admin === 'Singapore');

const members = {};   // region -> { own: [features], muni: [features] }
Object.keys(MAIN).forEach((id) => { members[id] = { own: byName(MAIN[id]), muni: [].concat(...(MUNI[id] || []).map(byName)) }; });
members.taiwan = { own: tw, muni: [] }; members.hongkong = { own: hk, muni: [] }; members.macau = { own: mo, muni: [] }; members.singapore = { own: sg, muni: [] };
Object.keys(members).forEach((id) => { if (!members[id].own.length) throw new Error('no features for ' + id); });

const fc = (feats) => ({ type: 'FeatureCollection', features: feats });
const tolFor = (id) => ({ xinjiang: 0.04, xizang: 0.04, neimenggu: 0.04, qinghai: 0.03, gansu: 0.03, heilongjiang: 0.03 }[id] || 0.015);

// ---- country map: Albers over the mainland, Taiwan, Hong Kong, Macau ----
const W = 350, H = 290;
const SMALL = ['hongkong', 'macau', 'singapore'];
const mapFeats = [];
Object.keys(members).filter((id) => SMALL.indexOf(id) < 0).forEach((id) => members[id].own.concat(members[id].muni).forEach((f) => mapFeats.push(simp(f, 0.03))));
const mainFeats = mapFeats.filter((f) => P(f).admin !== 'Taiwan');
const proj = d3.geoAlbers().rotate([-105, 0]).center([0, 36]).parallels([27, 45]).fitExtent([[4, 4], [W - 4, H - 4]], fc(mapFeats.filter((f) => !/Hong Kong|Macau/.test(P(f).admin))));
const path = d3.geoPath(proj).digits(1);
const out = { W, H, regions: {} };
Object.keys(members).forEach((id) => {
  const m = members[id];
  const tol = id === 'taiwan' ? 0.01 : 0.03;
  const r = { };
  if (SMALL.indexOf(id) < 0 || id === 'hongkong' || id === 'macau') {
    r.cd = m.own.map((f) => path(simp(f, id === 'hongkong' ? 0.003 : id === 'macau' ? 0 : tol))).filter(Boolean).join('');
    r.cm = m.muni.map((f) => path(simp(f, 0.02))).join('');
    const cen = path.centroid(fc(m.own.concat(m.muni)));
    r.cc = cen.map((v) => Math.round(v * 10) / 10);
  }
  out.regions[id] = r;
});

// ---- province maps: one Mercator fit per region, with the numbers needed to place pins ----
const PW = 360, PH = 300;
Object.keys(members).forEach((id) => {
  const m = members[id];
  const tol = tolFor(id);
  const own = m.own.map((f) => simp(f, SMALL.indexOf(id) >= 0 || id === 'taiwan' ? 0.001 : tol));
  const mun = m.muni.map((f) => simp(f, 0.005));
  const all = fc(own.concat(mun));
  const p = d3.geoMercator().fitExtent([[8, 8], [PW - 8, PH - 8]], all);
  const pa = d3.geoPath(p).digits(1);
  const r = out.regions[id];
  r.d = own.map((f) => pa(f)).filter(Boolean).join('');
  r.m = mun.map((f) => pa(f)).filter(Boolean).join('');
  const t = p.translate();
  r.k = Math.round(p.scale() * 100) / 100; r.tx = Math.round(t[0] * 100) / 100; r.ty = Math.round(t[1] * 100) / 100;
});

// ---- small insets for the strip on the country map ----
const inset = (feats, tol, size) => { const col = fc(feats.map((f) => simp(f, tol))); const p = d3.geoMercator().fitExtent([[4, 4], [size - 4, size - 4]], col); const pa = d3.geoPath(p).digits(1); return col.features.map((f) => pa(f)).join(''); };
out.insets = { hongkong: inset(hk, 0.002, 64), macau: inset(mo, 0, 64), singapore: inset(sg, 0.001, 64) };

const js = '/* GENERATED by tools/journey-map-gen.js from Natural Earth admin-1 (public domain). Do not edit by hand.\n * regions[id]: cd = outline on the country map, cm = municipality piece(s) on the country map, cc = label point,\n * d = province outline, m = municipality piece(s) inside it, k/tx/ty = Mercator numbers for placing pins (x = tx + k*lon_rad, y = ty - k*ln(tan(pi/4 + lat_rad/2))). */\nwindow.JOURNEY_MAP = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(process.argv[3] || '/tmp/geo/journey-map.js', js);
console.log('bytes', js.length, Object.keys(out.regions).length, 'regions');
Object.keys(out.regions).forEach((id) => { const r = out.regions[id]; console.log(id, (r.d || '').length, (r.cd || '').length); });
