#!/usr/bin/env python3
"""Build data/hsk1-erhua.js (the table behind the "儿 endings" switch) from content/erhua.tsv and content/erhua-overrides.tsv.
Run:  python3 tools/build-erhua.py
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
C = os.path.join(ROOT, 'content')


def rows(name):
    out = []
    for line in open(os.path.join(C, name), encoding='utf-8'):
        if line.strip() and not line.startswith('#'):
            out.append(line.rstrip('\n').split('\t'))
    return out


pairs = []
for r in rows('erhua.tsv'):
    if len(r) != 5 or r[4] not in ('yes', 'no'):
        sys.exit('build-erhua: bad row in erhua.tsv: %r' % (r,))
    pairs.append(dict(official=r[0], plain=r[1], officialPy=r[2], plainPy=r[3], twin=r[4] == 'yes'))
overrides = []
for r in rows('erhua-overrides.tsv'):
    if len(r) != 2:
        sys.exit('build-erhua: bad row in erhua-overrides.tsv: %r' % (r,))
    overrides.append(dict(from_=r[0], to=r[1]))

with open(os.path.join(ROOT, 'data', 'hsk1-erhua.js'), 'w', encoding='utf-8') as f:
    f.write('/* The words that have a northern 儿 ending on the official list, and their plain forms. GENERATED by tools/build-erhua.py from content/erhua.tsv. Do not edit by hand. */\n')
    f.write('window.HSK1_ERHUA = ' + json.dumps(dict(pairs=pairs, overrides=overrides), ensure_ascii=False, indent=1).replace('"from_"', '"from"') + ';\n')
print('hsk1-erhua.js: %d words, %d overrides' % (len(pairs), len(overrides)))
